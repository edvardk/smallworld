#!/usr/bin/env python3
"""The world map's block colour table, dumped from the pinned server jar's block registry (v1.4).

    map_palette.py dump  [--jdk DIR] [--server-jar FILE] [--vanilla-jar FILE] [--cache DIR]
    map_palette.py check [--jdk DIR] [--server-jar FILE] [--vanilla-jar FILE] [--cache DIR]

Writes server-config/keys/<minecraft_version>/map-palette.tsv (every block state's map colour, fluid flag and
the colour the map records when it stops on it) and map-colors.tsv (each map colour's base RGB); `check`
regenerates both and fails on any difference. The format is in docs/reference.md "World map".

How: rebuild the server jar offline exactly as scripts/config_keys.py does (pinned paperclip + the vanilla jar
it names, every step sha256-checked), extract the libraries paperclip's META-INF/libraries.list names (each
sha256-checked), compile scripts/map_palette/Dump.java with the JDK pinned in plugin/mc-brand/build.yml and
run it in a throwaway directory. The classpath is only those pinned jars, and the JVM has no network (a
private network namespace via `unshare -rn` where the kernel allows it, else proxy properties that point
nowhere).

This is the documented exception to "never run the jar" (CLAUDE.md "Config keys"): Dump bootstraps the block
registry (`Bootstrap.bootStrap()`) and reads it; it never starts the server, opens a world or uses the
network.
CI runs `check` in ci.yml job plugin, with the jars cached like build_plugin.py's.
"""

from __future__ import annotations

import argparse
import io
import json
import os
import re
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

import build_plugin
from config_keys import KEYS_DIR, build_server_jar
from lockfile import REPO_ROOT, SERVER_LOCK, digest, download_verified, load_yaml

DUMPER = REPO_ROOT / "scripts" / "map_palette" / "Dump.java"
JDK_BUILD = "mc-brand"  # the plugin whose build.yml pins the JDK (and javac --release)
FORMAT = 1
STATE = re.compile(r"^Block\{([a-z0-9_.-]+:[a-z0-9_./-]+)\}(?:\[([^\]]*)\])?$")
PALETTE_HEADER = """\
# The world map's block palette (docs/reference.md "World map"). Generated by scripts/map_palette.py from the
# pinned server jar's block registry: do not edit, re-run `map_palette.py dump` after a version bump.
# One record per line, tab-separated; the first field is the record kind:
#   M  key  value                                  metadata
#   D  block  properties  colour  fluid  surface   a block's default state (every block, registry order)
#   S  block  properties  colour  fluid  surface   a state of the D line above whose last three fields differ
# properties: k=v pairs sorted by name, comma-separated, "-" for a block without properties. A state with no
#   S line has its block's D values.
# colour: MapColor id (BlockState.getMapColor); 0 = NONE, the map looks through it to the block below.
# fluid: 1 if the state has a fluid (water, lava, waterlogged): the map counts water depth below it.
# surface: the MapColor id the map records when it stops on this state (MapItem.getCorrectStateForFluidBlock:
#   a state with a fluid and no sturdy top face counts as its fluid's block: WATER 12, lava FIRE 4).
"""
COLORS_HEADER = """\
# The world map's base colours (docs/reference.md "World map"). Generated by scripts/map_palette.py from the
# pinned server jar (MapColor): do not edit. id TAB rrggbb. Shaded colour = channel * m // 255,
# m = 180, 220, 255, 135 for brightness 0..3; packed id = colour * 4 + brightness.
"""


def vanilla_jar(paperclip: bytes, path: str | None, cache: Path) -> bytes:
    """The vanilla server jar paperclip patches (META-INF/download-context: sha256, URL, file name), from
    --vanilla-jar, the cache or Mojang; always sha256-checked."""
    with zipfile.ZipFile(io.BytesIO(paperclip)) as z:
        sha, url, name = z.read("META-INF/download-context").decode().split()
    if path:
        data = Path(path).read_bytes()
        if digest(data, "sha256") != sha:
            raise SystemExit(f"{path}: sha256 differs from the pinned server jar's download-context ({name})")
        return data
    cached = cache / name
    if cached.is_file() and digest(cached.read_bytes(), "sha256") == sha:
        return cached.read_bytes()
    data = download_verified(url, {"sha256": sha})
    cache.mkdir(parents=True, exist_ok=True)
    cached.write_bytes(data)
    return data


def libraries(paperclip: bytes, vanilla: bytes, dest: Path) -> list[Path]:
    """Every library of paperclip's META-INF/libraries.list (sha256 TAB coordinates TAB path), taken from the
    paperclip or the vanilla jar's META-INF/libraries/ and sha256-checked, extracted to `dest`."""
    zips = [zipfile.ZipFile(io.BytesIO(paperclip)), zipfile.ZipFile(io.BytesIO(vanilla))]
    out = []
    for line in zips[0].read("META-INF/libraries.list").decode().splitlines():
        sha, _coords, rel = line.split("\t")
        member = f"META-INF/libraries/{rel}"
        data = next((z.read(member) for z in zips if member in z.namelist()), None)
        if data is None:
            raise SystemExit(f"library {rel} is in neither pinned jar")
        if digest(data, "sha256") != sha:
            raise SystemExit(f"library {rel}: sha256 mismatch")
        p = dest / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
        out.append(p)
    return out


def _isolation() -> list[str]:
    """argv prefix that runs a command without network: a fresh user + network namespace when the kernel
    allows unprivileged ones (not on every CI runner), else nothing (the JVM gets dead proxies instead)."""
    try:
        ok = subprocess.run(["unshare", "-rn", "true"], capture_output=True, timeout=10).returncode == 0
    except (OSError, subprocess.SubprocessError):
        ok = False
    return ["unshare", "-rn"] if ok else []


DEAD_PROXIES = [  # discard-port proxies: java.net URL connections fail instead of reaching out
    "-Dhttp.proxyHost=127.0.0.1", "-Dhttp.proxyPort=9", "-Dhttps.proxyHost=127.0.0.1", "-Dhttps.proxyPort=9",
    "-DsocksProxyHost=127.0.0.1", "-DsocksProxyPort=9", "-Djava.net.useSystemProxies=false",
]  # fmt: skip


def run_dumper(jdk: Path, release: int, classpath: list[Path], tmp: Path) -> tuple[str, str]:
    """Compile and run Dump.java in `tmp`: (states text, colours text)."""
    env = build_plugin._env()
    for k in list(env):
        if k.lower() in ("http_proxy", "https_proxy", "all_proxy", "no_proxy"):
            del env[k]
    cp = os.pathsep.join(map(str, classpath))
    classes = tmp / "classes"
    classes.mkdir()
    res = subprocess.run(
        [str(jdk / "bin" / "javac"), "--release", str(release), "-proc:none", "-encoding", "UTF-8",
         "-d", str(classes), "-cp", cp, str(DUMPER)],
        capture_output=True, text=True, env=env, cwd=tmp,
    )  # fmt: skip
    if res.returncode != 0:
        sys.stderr.write(res.stdout + res.stderr)
        raise SystemExit("javac Dump.java failed")
    prefix = _isolation()
    print("map_palette: running the registry dump " + ("in a private network namespace" if prefix else
          "with dead proxies (no unprivileged network namespace here)"), file=sys.stderr)  # fmt: skip
    work = tmp / "run"
    work.mkdir()
    res = subprocess.run(
        [*prefix, str(jdk / "bin" / "java"), "-Xmx1g", "-XX:+UseSerialGC", "-Djava.awt.headless=true",
         f"-Djava.io.tmpdir={work}", *DEAD_PROXIES, "-cp", os.pathsep.join([str(classes), cp]),
         "Dump", "states.tsv", "colors.tsv"],
        capture_output=True, text=True, env=env, cwd=work, timeout=600,
    )  # fmt: skip
    if res.returncode != 0:
        sys.stderr.write(res.stdout[-4000:] + res.stderr[-4000:])
        raise SystemExit("Dump failed")
    return (work / "states.tsv").read_text(), (work / "colors.tsv").read_text()


def palette_text(states: str, meta: dict[str, str]) -> tuple[str, dict[str, int]]:
    """The committed map-palette.tsv from Dump's states output, plus stats."""
    blocks: dict[
        str, list[tuple[str, str, bool]]
    ] = {}  # block -> [(props, "colour\tfluid\tsurface", default)]
    for line in states.splitlines():
        state, colour, fluid, surface, default = line.split("\t")
        m = STATE.match(state)
        if not m:
            raise SystemExit(f"unexpected state string: {state!r}")
        name, props = m.group(1), m.group(2) or "-"
        if props != "-":
            pairs = props.split(",")
            if pairs != sorted(pairs, key=lambda kv: kv.split("=")[0]):
                raise SystemExit(f"{state}: properties not sorted")
        blocks.setdefault(name, []).append((props, f"{colour}\t{fluid}\t{surface}", default == "1"))
    lines = [PALETTE_HEADER.rstrip("\n")]
    nstates = sum(len(v) for v in blocks.values())
    meta = {"format": str(FORMAT), **meta, "blocks": str(len(blocks)), "states": str(nstates)}
    lines += [f"M\t{k}\t{v}" for k, v in meta.items()]
    stats = {"blocks": len(blocks), "states": nstates, "exceptions": 0, "see_through_blocks": 0}
    stats |= {"fluid_blocks": 0, "state_dependent_blocks": 0}
    for name, rows in blocks.items():
        defaults = [r for r in rows if r[2]]
        if len(defaults) != 1:
            raise SystemExit(f"{name}: {len(defaults)} default states")
        dprops, dvals, _ = defaults[0]
        lines.append(f"D\t{name}\t{dprops}\t{dvals}")
        stats["see_through_blocks"] += dvals.split("\t")[0] == "0"
        stats["fluid_blocks"] += dvals.split("\t")[1] == "1"
        exceptions = [(p, v) for p, v, d in rows if not d and v != dvals]
        lines += [f"S\t{name}\t{p}\t{v}" for p, v in exceptions]
        stats["exceptions"] += len(exceptions)
        stats["state_dependent_blocks"] += any(
            v.split("\t")[0] != dvals.split("\t")[0] for _, v in exceptions
        )
    return "\n".join(lines) + "\n", stats


def colors_text(colors: str) -> str:
    rows = [line.split("\t") for line in colors.splitlines()]
    ids = [int(i) for i, _ in rows]
    if ids != list(range(len(ids))):
        raise SystemExit(f"map colour ids are not 0..n-1: {ids}")
    return COLORS_HEADER + "".join(f"{i}\t{int(h, 16):06x}\n" for i, h in rows)


def generate(args: argparse.Namespace) -> tuple[dict[str, str], dict[str, int], str]:
    """({file name: text}, stats, minecraft_version)."""
    cache = Path(args.cache)
    cache.mkdir(parents=True, exist_ok=True)
    lock = load_yaml(SERVER_LOCK)
    paperclip = build_plugin.server_jar(args.server_jar, cache)
    vanilla = vanilla_jar(paperclip, args.vanilla_jar, cache)
    build = build_plugin.load_build(JDK_BUILD)
    if int(build["release"]) != int(lock["java_major"]):
        raise SystemExit(f"plugin/{JDK_BUILD}/build.yml release != java_major (template/server.lock.yml)")
    jdk = build_plugin.jdk_home(args.jdk, build, cache)
    with tempfile.TemporaryDirectory(prefix="map-palette-") as tmpdir:
        tmp = Path(tmpdir)
        server = tmp / "server.jar"
        server.write_bytes(build_server_jar(paperclip, vanilla))
        with zipfile.ZipFile(server) as z:
            version = json.loads(z.read("version.json"))
        mc = str(lock["minecraft_version"])
        if version["id"] != mc:
            raise SystemExit(f"server jar is {version['id']}, server.lock.yml pins {mc}")
        cp = [server, *libraries(paperclip, vanilla, tmp / "lib")]
        states, colors = run_dumper(jdk, int(build["release"]), cp, tmp)
    meta = {
        "minecraft_version": mc,
        "data_version": str(version["world_version"]),
        "server": str(lock["server"]["filename"]),
    }
    palette, stats = palette_text(states, meta)
    files = {"map-palette.tsv": palette, "map-colors.tsv": colors_text(colors)}
    stats["colours"] = len(colors.splitlines())
    return files, stats, mc


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("command", choices=["dump", "check"])
    ap.add_argument("--jdk", help="JDK home with the pinned javac (default: download the pinned Temurin)")
    ap.add_argument("--server-jar", help="the pinned server jar (paperclip; default: download it)")
    ap.add_argument("--vanilla-jar", help="the vanilla jar the server jar names (default: download it)")
    ap.add_argument("--cache", default=str(Path.home() / ".cache" / "smallworld" / "build-plugin"))
    args = ap.parse_args(argv)
    files, stats, mc = generate(args)
    out_dir = KEYS_DIR / mc
    print("map_palette: " + ", ".join(f"{k} {v}" for k, v in stats.items()))
    if args.command == "dump":
        out_dir.mkdir(parents=True, exist_ok=True)
        for name, text in files.items():
            (out_dir / name).write_text(text)
            print(f"wrote {(out_dir / name).relative_to(REPO_ROOT)}")
        return 0
    bad = [n for n, t in files.items() if not (out_dir / n).is_file() or (out_dir / n).read_text() != t]
    for name in bad:
        print(
            f"server-config/keys/{mc}/{name} differs from a fresh dump: run map_palette.py dump",
            file=sys.stderr,
        )
    if not bad:
        print(f"server-config/keys/{mc}/map-palette.tsv, map-colors.tsv: up to date")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
