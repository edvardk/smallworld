#!/usr/bin/env python3
"""v1.1: client.lock.yml for the client modpack (client/pack.yml), and its upstream verification.

    client_pack.py lock [--lock-dir DIR] [--minecraft-version V]   # newest builds -> DIR/client.lock.yml
    client_pack.py verify BASE_DIR HEAD_DIR                         # what verify_lock_update.py runs for it

`lock` (called by update_lock.py, so the weekly update job and `mcctl lock update` refresh it with the other
locks): per entry of client/pack.yml the newest Modrinth *release* for the pinned Minecraft version and Fabric
(shader packs: the iris loader), downloaded and checked against the API's sha1/sha512, its sha256 computed
(the R2 mirror key), the project's licence and source link, and for mods the fabric.mod.json id, `provides`,
nested jar ids and `depends`. An entry without such a build is `pending` (it joins the packs once one exists);
an entry whose required mods aren't all present in a tier is pending too ("needs ..."). The Fabric loader is
the newest stable one for the version (meta.fabricmc.net). `mirror` is true only if client/pack.yml allows
it for the entry and its licence is in `redistributable`. v1.2: an `inhouse` entry (the Smallworld
client mod) is the product's committed jar, hashed here; it has no upstream URL
(the mirror is its only download).

`verify`: the same set of entries; each changed one is a newer release of the same project for this Minecraft
version, its file and hashes exactly the API's (downloaded and re-hashed), its licence and mirror flag
unchanged (an in-house one: exactly the product's jar); a changed loader is a stable Fabric loader for the
version. Exit 0 = may merge, 1 = the reasons.
"""

from __future__ import annotations

import argparse
import io
import json
import sys
import urllib.parse
import zipfile
from pathlib import Path
from typing import Any

from lockfile import LOCK_DIR, REPO_ROOT, digest, download_verified, dump_yaml, get_json, load_yaml

sys.path.insert(0, str(REPO_ROOT))
from mcctl import clientpack, configrepo

MODRINTH_API = "https://api.modrinth.com/v2"
FABRIC_META = "https://meta.fabricmc.net/v2"
FABRIC_MAVEN = "https://maven.fabricmc.net/net/fabricmc/fabric-loader"
FABRIC_PROFILE = FABRIC_META + "/versions/loader/{mc}/{loader}/profile/json"
BUILTIN_IDS = {"minecraft", "fabricloader", "java", "fabric-loader"}
HEADER = """\
# Pinned client modpack (v1.1). Generated by the product's scripts/client_pack.py - do not hand-edit hashes.
# Entries come from the product's client/pack.yml; `pending` ones have no release for this Minecraft version
# yet."""


def _q(params: dict[str, Any]) -> str:
    return urllib.parse.urlencode({k: json.dumps(v) if isinstance(v, list) else v for k, v in params.items()})


def fabric_meta(data: bytes) -> dict[str, Any]:
    """id, provides (own + nested jars') and depends of a Fabric mod jar ({} for anything else)."""
    try:
        with zipfile.ZipFile(io.BytesIO(data)) as z:
            meta = json.loads(z.read("fabric.mod.json"))
            provides = {str(meta.get("id"))} | {str(p) for p in meta.get("provides") or []}
            for j in meta.get("jars") or []:
                with zipfile.ZipFile(io.BytesIO(z.read(j["file"]))) as nested:
                    n = json.loads(nested.read("fabric.mod.json"))
                    provides |= {str(n.get("id"))} | {str(p) for p in n.get("provides") or []}
    except (KeyError, zipfile.BadZipFile, ValueError):
        return {}
    depends = meta.get("depends") or {}
    return {
        "mod_id": str(meta.get("id")),
        "provides": sorted(provides),
        "depends": sorted(str(k) for k in depends),
    }


def inhouse_entry(entry: dict[str, Any], d: dict[str, Any]) -> dict[str, Any]:
    """v1.2: an in-house mod (client/pack.yml `inhouse`): the product's committed jar, pinned like any."""
    data, build = clientpack.inhouse_jar(entry)
    licence = clientpack.inhouse_licence(data)
    repo = f"https://github.com/{configrepo.PRODUCT_REPOSITORY}"
    out: dict[str, Any] = {
        "slug": entry["slug"],
        "name": entry["name"],
        "kind": "mod",
        "source": "inhouse",
        "project_url": repo,
        "source_url": f"{repo}/tree/main/{Path(entry['inhouse']['build']).parent.as_posix()}",
        "licence": licence,
        "version": str(build["version"]),
        "path": entry["inhouse"]["jar"],
        "filename": clientpack.inhouse_filename(entry, build),
        "url": "",
        "size": len(data),
        "sha1": digest(data, "sha1"),
        "sha512": digest(data, "sha512"),
        "sha256": digest(data, "sha256"),
        "mirror": licence in d["redistributable"],
        "tiers": clientpack.entry_tiers(entry),
    }
    out.update(fabric_meta(data))
    return out


def resolve_entry(
    entry: dict[str, Any], kind: str, mc_version: str, d: dict[str, Any]
) -> dict[str, Any] | str:
    if entry.get("inhouse"):
        return inhouse_entry(entry, d)
    slug = entry["slug"]
    loaders = ["iris"] if kind == "shader" else ["fabric"]
    versions = get_json(
        f"{MODRINTH_API}/project/{slug}/version?"
        + _q({"loaders": loaders, "game_versions": [mc_version], "include_changelog": "false"})
    )
    releases = [v for v in versions if v.get("version_type") == "release"]
    if not releases:
        if versions:  # v1.2: say why (only betas/alphas: the packs take releases only)
            newest = max(versions, key=lambda x: x["date_published"])
            return (
                f"only {newest.get('version_type')} builds for Minecraft {mc_version} + {loaders[0]} on "
                f"Modrinth (newest {newest.get('version_number')}); the packs take releases only"
            )
        return f"no release for Minecraft {mc_version} + {loaders[0]} on Modrinth yet"
    v = max(releases, key=lambda x: x["date_published"])
    f = next((f for f in v["files"] if f.get("primary")), v["files"][0])
    data = download_verified(f["url"], {"sha512": f["hashes"]["sha512"], "sha1": f["hashes"]["sha1"]})
    project = get_json(f"{MODRINTH_API}/project/{slug}")
    licence = str((project.get("license") or {}).get("id") or "")
    out: dict[str, Any] = {
        "slug": slug,
        "name": entry["name"],
        "kind": kind,
        "project_id": project["id"],
        "project_url": f"https://modrinth.com/{project.get('project_type', 'mod')}/{slug}",
        "source_url": project.get("source_url") or "",
        "licence": licence,
        "version": v["version_number"],
        "version_id": v["id"],
        "published": v["date_published"],
        "filename": f["filename"],
        "url": f["url"],
        "size": len(data),
        "sha1": f["hashes"]["sha1"],
        "sha512": f["hashes"]["sha512"],
        "sha256": digest(data, "sha256"),
        "mirror": bool(entry.get("mirror", True)) and licence in d["redistributable"],
        "tiers": clientpack.entry_tiers(entry),
    }
    if kind == "mod":
        out.update(fabric_meta(data))
    return out


def drop_unmet(
    files: list[dict[str, Any]], pending: list[dict[str, Any]], builtin: set[str] | None = None
) -> None:
    """Per tier, a mod whose `depends` aren't provided by the tier's mods is taken out of that tier; one left
    in no tier is pending ("needs ..."). Repeated until nothing changes (a dropped mod may be another's
    dependency)."""
    changed = True
    while changed:
        changed = False
        for f in files:
            for tier in list(f["tiers"]):
                provided = (
                    BUILTIN_IDS
                    | (builtin or set())
                    | {i for g in files if tier in g["tiers"] for i in g.get("provides", [])}
                )
                missing = [dep for dep in f.get("depends", []) if dep not in provided]
                if missing:
                    f["tiers"].remove(tier)
                    f.setdefault("_missing", set()).update(missing)
                    changed = True
    for f in [f for f in files if not f["tiers"]]:
        files.remove(f)
        pending.append({"slug": f["slug"], "reason": "needs " + ", ".join(sorted(f.pop("_missing")))})
    for f in files:
        f.pop("_missing", None)


def fabric_loader(mc_version: str) -> str:
    for entry in get_json(f"{FABRIC_META}/versions/loader/{urllib.parse.quote(mc_version)}"):
        if entry["loader"].get("stable"):
            return str(entry["loader"]["version"])
    raise LookupError(f"no stable Fabric loader for Minecraft {mc_version}")


def loader_profile(mc_version: str, version: str) -> dict[str, Any]:
    """v1.2: the official launcher's version profile for Fabric (versions/<id>/<id>.json in the launcher zip),
    pinned in the lock with its sha256 so the packs are built from the lock alone. The stored JSON must give
    the downloaded bytes back exactly (clientpack.profile_bytes)."""
    url = FABRIC_PROFILE.format(mc=urllib.parse.quote(mc_version), loader=urllib.parse.quote(version))
    from lockfile import http_get

    raw = http_get(url)
    data = json.loads(raw)
    profile = {"id": str(data.get("id")), "url": url, "sha256": digest(raw, "sha256"), "json": data}
    if clientpack.profile_bytes(profile) != raw or profile["id"] != f"fabric-loader-{version}-{mc_version}":
        raise LookupError(f"{url}: the profile doesn't round-trip (or has another id): can't pin it")
    return profile


def loader_provides(version: str) -> list[str]:
    """The ids the loader itself provides (its nested jars, e.g. mixinextras): the jar from Fabric's maven,
    checked against the maven's .sha1."""
    url = f"{FABRIC_MAVEN}/{version}/fabric-loader-{version}.jar"
    from lockfile import http_get

    sha1 = http_get(url + ".sha1").decode().split()[0]
    return fabric_meta(download_verified(url, {"sha1": sha1})).get("provides", [])


def resolve(mc_version: str, d: dict[str, Any] | None = None) -> dict[str, Any]:
    d = d or clientpack.load_definition()
    if str(mc_version) not in {str(k) for k in d["data_versions"]}:
        raise LookupError(
            f"client/pack.yml data_versions has no entry for Minecraft {mc_version} (a product change)"
        )
    files: list[dict[str, Any]] = []
    pending: list[dict[str, Any]] = []
    for kind, entry in [("mod", m) for m in d["mods"]] + [("shader", d["shader"])]:
        got = resolve_entry(entry, kind, mc_version, d)
        if isinstance(got, str):
            pending.append({"slug": entry["slug"], "reason": got})
        else:
            files.append(got)
    loader = fabric_loader(mc_version)
    provides = loader_provides(loader)
    drop_unmet(files, pending, set(provides))
    return {
        "minecraft_version": str(mc_version),
        "loader": {
            "name": "fabric",
            "version": loader,
            "provides": provides,
            "profile": loader_profile(str(mc_version), loader),
        },
        "files": files,
        "pending": pending,
    }


def write_lock(lock_dir: Path, mc_version: str) -> dict[str, Any]:
    lock = resolve(mc_version)
    dump_yaml(lock_dir / clientpack.LOCK_FILE, lock, HEADER)
    return lock


# --- verify (the gate) ----------------------------------------------------------------------------------


def _same_set(base: dict[str, Any], head: dict[str, Any]) -> bool:
    def slugs(lock: dict[str, Any]) -> set[str]:
        return {f["slug"] for f in lock.get("files") or []} | {p["slug"] for p in lock.get("pending") or []}

    return slugs(base) == slugs(head)


def check_entry(
    new: dict[str, Any], old: dict[str, Any] | None, mc_version: str, d: dict[str, Any]
) -> list[str]:
    name = new.get("slug")
    entry = next((m for m in [*d["mods"], d["shader"]] if m["slug"] == name), None)
    if entry is None:
        return [f"client.lock.yml {name}: not in client/pack.yml"]
    if entry.get("inhouse"):  # v1.2: exactly the product's committed jar, nothing upstream to ask
        if new != inhouse_entry(entry, d):
            jar = entry["inhouse"]["jar"]
            return [f"client.lock.yml {name}: isn't the product's {jar} (run the lock tool)"]
        return []
    v = get_json(f"{MODRINTH_API}/version/{urllib.parse.quote(str(new.get('version_id', '')))}")
    project = get_json(f"{MODRINTH_API}/project/{urllib.parse.quote(str(name))}")
    if v.get("project_id") != project.get("id") or new.get("project_id") != project.get("id"):
        return [f"client.lock.yml {name}: version {new.get('version_id')} isn't from modrinth:{name}"]
    if v.get("version_type") != "release" or mc_version not in (v.get("game_versions") or []):
        return [
            f"client.lock.yml {name}: {v.get('version_number')} isn't a release for Minecraft {mc_version}"
        ]
    f = next((f for f in v.get("files") or [] if f.get("url") == new.get("url")), None)
    if not f or f.get("filename") != new.get("filename") or f["hashes"].get("sha512") != new.get("sha512"):
        return [f"client.lock.yml {name}: url/filename/sha512 aren't a file of that version"]
    licence = str((project.get("license") or {}).get("id") or "")
    if licence != new.get("licence") or (old and old.get("licence") != licence):
        return [f"client.lock.yml {name}: the licence changed ({licence!r}): a human checks the new terms"]
    if new.get("mirror") != (bool(entry.get("mirror", True)) and licence in d["redistributable"]):
        return [f"client.lock.yml {name}: mirror flag doesn't follow client/pack.yml"]
    if old is not None:
        ov = get_json(f"{MODRINTH_API}/version/{urllib.parse.quote(str(old.get('version_id', '')))}")
        if ov.get("project_id") != project.get("id"):
            return [f"client.lock.yml {name}: the base's version isn't from modrinth:{name}"]
        from verify_lock_update import newer_release

        if reasons := newer_release(
            f"client.lock.yml {name}", v.get("date_published"), ov.get("date_published")
        ):
            return reasons
    download_verified(
        str(new["url"]),
        {"sha512": str(new["sha512"]), "sha1": str(new["sha1"]), "sha256": str(new["sha256"])},
    )
    return []


def verify(base: dict[str, Any] | None, head: dict[str, Any] | None) -> list[str]:
    """None = the file doesn't exist on that side."""
    if head is None:
        return [] if base is None else ["client.lock.yml was removed: that needs a human"]
    if base is None:
        return ["client.lock.yml is new: the first client lock needs a human"]
    d = clientpack.load_definition()
    mc = str(head.get("minecraft_version"))
    if mc != str(base.get("minecraft_version")):
        return ["client.lock.yml minecraft_version changed: that needs a human"]
    if not _same_set(base, head):
        return ["client.lock.yml: the set of entries changed (client/pack.yml did): that needs a human"]
    reasons = clientpack.lock_errors(head, mc, d)
    if reasons:
        return reasons
    if head.get("loader") != base.get("loader"):
        if str(head["loader"]["version"]) != fabric_loader(mc):
            reasons.append("client.lock.yml loader isn't the newest stable Fabric loader for this version")
        elif head["loader"].get("profile") != loader_profile(mc, str(head["loader"]["version"])):
            reasons.append("client.lock.yml loader profile isn't Fabric meta's profile for this loader")
    old = {f["slug"]: f for f in base.get("files") or []}
    for f in head.get("files") or []:
        if old.get(f["slug"]) != f:
            reasons += check_entry(f, old.get(f["slug"]), mc, d)
    return reasons


def _load(path: Path) -> dict[str, Any] | None:
    return load_yaml(path) if path.is_file() else None


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="command", required=True)
    lk = sub.add_parser("lock")
    lk.add_argument("--lock-dir", type=Path, default=LOCK_DIR)
    lk.add_argument("--minecraft-version")
    vf = sub.add_parser("verify")
    vf.add_argument("base", type=Path)
    vf.add_argument("head", type=Path)
    args = ap.parse_args(argv)
    if args.command == "lock":
        mc = args.minecraft_version or str(load_yaml(args.lock_dir / "server.lock.yml")["minecraft_version"])
        lock = write_lock(args.lock_dir, mc)
        for f in lock["files"]:
            print(f"client: {f['slug']} {f['version']} ({f['licence']}{', mirrored' if f['mirror'] else ''})")
        for p in lock["pending"]:
            print(f"client: {p['slug']} pending: {p['reason']}")
        return 0
    reasons = verify(_load(args.base / clientpack.LOCK_FILE), _load(args.head / clientpack.LOCK_FILE))
    for r in reasons:
        print(r)
    return 1 if reasons else 0


if __name__ == "__main__":
    sys.exit(main())
