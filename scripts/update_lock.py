#!/usr/bin/env python3
"""Bump server.lock.yml, plugins.lock.yml and (v1.1) client.lock.yml to the latest builds for a Minecraft
version.

    update_lock.py                          # latest builds for the currently pinned MC version
    update_lock.py --minecraft-version 26.3 # move to a new MC version (ask the maintainer first!)
    update_lock.py --allow-paper            # permit switching to Paper if Purpur has no build
    update_lock.py --lock-dir ../my-config  # a config repo's locks (default: the product's template/)
    update_lock.py --client                 # also create client.lock.yml (before turning client.enabled on)

Fails without writing anything if any plugin has no release for the target version, so a
version bump can't silently drop a plugin. Review the diff, then open a PR (the update-lock
workflow does this for you).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import client_pack
import fetch_plugins
import fetch_server_jar
from lockfile import LOCK_DIR, dump_yaml, load_yaml

SERVER_HEADER = """\
# Pinned server build. Generated by the product's scripts/update_lock.py - do not hand-edit hashes.
# Changing minecraft_version is a human decision (must be >= the world's version; server.yml must match)."""

PLUGINS_HEADER = """\
# Pinned plugins. Generated by the product's scripts/update_lock.py - do not hand-edit hashes.
# To add a plugin: append {name, source: modrinth|hangar, project} and re-run update_lock.py."""


def client_enabled(lock_dir: Path) -> bool:
    """server.yml next to the locks says client.enabled: true (a config repo; the product's template
    doesn't)."""
    path = lock_dir / "server.yml"
    try:
        data = load_yaml(path) if path.is_file() else {}
    except (OSError, ValueError):
        return False
    return bool(isinstance(data, dict) and ((data.get("client") or {}).get("enabled") is True))


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--minecraft-version", help="target MC version (default: currently pinned)")
    p.add_argument(
        "--allow-paper",
        action="store_true",
        help="fall back to Paper if Purpur has no successful build for the version (default: fail)",
    )
    p.add_argument("--lock-dir", type=Path, default=LOCK_DIR, help="directory holding the lock files")
    p.add_argument(
        "--client",
        action="store_true",
        help="also write client.lock.yml where there is none yet (v1.2: needed before client.enabled: true)",
    )
    args = p.parse_args(argv)
    server_lock, plugins_lock = args.lock_dir / "server.lock.yml", args.lock_dir / "plugins.lock.yml"

    current = load_yaml(server_lock)
    mc_version = args.minecraft_version or current["minecraft_version"]

    server = fetch_server_jar.resolve(mc_version, args.allow_paper)
    plugins = [fetch_plugins.resolve(pl, mc_version) for pl in load_yaml(plugins_lock)["plugins"]]

    # v1.1: the client pack's lock, where there is one, server.yml turns the client on, or (v1.2) --client
    # asks for a first one: resolved before writing anything, so a failure leaves every lock as it was
    client_lock = args.lock_dir / client_pack.clientpack.LOCK_FILE
    wanted = args.client or client_lock.is_file() or client_enabled(args.lock_dir)
    client = client_pack.resolve(mc_version) if wanted else {"files": [], "pending": []}
    dump_yaml(server_lock, server, SERVER_HEADER)
    dump_yaml(plugins_lock, {"plugins": plugins}, PLUGINS_HEADER)
    if wanted:
        dump_yaml(client_lock, client, client_pack.HEADER)
    s = server["server"]
    print(f"server: {s['project']} {mc_version} build {s['build']} (java {server['java_major']})")
    for pl in plugins:
        print(f"plugin: {pl['name']} {pl['version']}")
    for f in client["files"]:
        print(f"client: {f['slug']} {f['version']}")
    for p in client["pending"]:
        print(f"client: {p['slug']} pending ({p['reason']})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
