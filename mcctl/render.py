def client_plans(repo: ConfigRepo) -> dict[str, dict[str, Any]]:
    cfg = repo.server
    if not cfg.client.enabled or repo.client_lock is None:
        return {}
    return clientpack.plans_for(
        repo.client_lock,
        server=cfg.branding.name or panel_title(cfg),
        address=server_address(cfg),
        view_distance=int(cfg.performance.view_distance or 10),
        resource_pack=cfg.branding.enabled and cfg.branding.resource_pack.enabled,
        tiers=list(cfg.client.tiers),
    )


def client_packs(repo: ConfigRepo) -> dict[str, str]:
    """v1.2: tier -> the current pack version id (what the client mod's hello must name, else mc-brand says
    the pack is outdated); empty while the client is off or has no lock."""
    return {tier: p["version_id"] for tier, p in client_plans(repo).items()}


