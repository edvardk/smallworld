def hologram(h: BrandingHologram) -> dict[str, Any]:
    """v1.2: one of Holograms.java's specs (block coordinates; the plugin centres the text); v1.3: `at: spawn`
    instead of x/y/z, and `help`."""
    where: dict[str, Any] = {"at": h.at} if h.at else {"x": h.x, "y": h.y, "z": h.z}
    return {"world": DIMENSIONS[h.world], **where, "lines": list(h.lines), "health": h.health, "help": h.help}


def gamerules(cfg: ServerConfig) -> dict[str, str]:
    """v1.2: game rule -> value as the `gamerule` command takes it (true/false or an integer): the social
    defaults from gameplay.* plus minecraft.gamerules (names without the minecraft: namespace)."""
    rules: dict[str, bool | int] = {
        "locator_bar": cfg.gameplay.locator_bar,
        "players_sleeping_percentage": cfg.gameplay.sleeping_percentage,
    }
    rules |= {k.removeprefix("minecraft:"): v for k, v in cfg.minecraft.gamerules.items()}
    return {k: (str(v).lower() if isinstance(v, bool) else str(v)) for k, v in sorted(rules.items())}


