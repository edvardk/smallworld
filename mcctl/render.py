def world_library(cfg: ServerConfig) -> dict[str, Any]:
    """v1.2: server.yml world.active/library for the minecraft role (worlds-library.json, the panel's pending
    change on top), entries as scripts/worlds.py check_entry reads them (border keys = dimension ids)."""
    lib = []
    for e in cfg.world.library:
        border = None if e.border_radius is None else dataclasses.asdict(e.border_radius)
        lib.append({
            "name": e.name, "seed": e.seed, "type": e.type, "preset": e.preset, "pregen": e.pregen,
            "border_radius": None if border is None else {DIMENSIONS[d]: r for d, r in border.items()},
        })  # fmt: skip
    return {"mc_world_active": cfg.world.active, "mc_world_library": lib}


def _helper_cpus(cfg: ServerConfig) -> str:
    """systemd AllowedCPUs of the product's helpers: CPU 0 with cpu_affinity split (the JVM gets 1..n-1, from
    the host's CPU count at deploy: the minecraft role), else performance.helper_cpus ("" = all)."""
    perf = cfg.performance
    return "0" if perf.cpu_affinity == "split" else perf.helper_cpus or ""


