"""`mcctl render`: a config repo -> the inputs the product's Terraform and Ansible run with (design §1, §2).

The product holds no deployment values: no tfvars, no backend values, no inventory, no tunables in
group_vars. Everything comes from here, written into one directory (default <config>/.mcctl/rendered):

    terraform/terraform.tfvars.json   terraform plan/apply -var-file=...
    terraform/state.tfbackend         terraform init -backend-config=...   (server.yml state.*)
    ansible/inventory.yml             ansible-playbook -i ...  (host = host.tailscale_name)
    ansible/group_vars/all.yml        loaded by Ansible next to that inventory: the server.yml tunables,
                                      players.yml (P10) and the two lock files (server_lock, plugins_lock)
    client/<tier>.plan.json, client/index.json
                                      v1.1 (client.enabled): the client packs as the Worker writes them
                                      (mcctl/clientpack.py); `mcctl client-publish` uploads them
    watchdog/                         v1.2: the watchdog Worker's static assets (terraform var
                                      watchdog_assets_dir, an absolute path in the tfvars): the product's
                                      watchdog/panel/ files plus pack/<sha1>.zip, the resource pack built
                                      from the config repo's art (mcctl/brandpack.py; mc_brand_pack_sha1)
                                      and v1.3's version.json: the product version and the config repo's
                                      pin, which `mcctl apply` uploads with worker.js (the panel's Versions
                                      row, `mcctl doctor`)

Only variables today's roles and root module read are rendered. Fields whose consumers arrive in later phases
(Grafana, automation, overrides) are validated but not rendered yet; the panel's (P9) and gamerules (v1.2)
are.
"""

