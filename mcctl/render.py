def _heap(cfg: ServerConfig) -> dict[str, int]:
    if cfg.jvm.heap_mb != "auto":
        return {"mc_heap_mb": int(cfg.jvm.heap_mb)}  # overrides the minecraft role's computed default
    onserver_stack = cfg.panel.mode == "onserver" or cfg.monitoring.grafana
    # P16: the same reserve for jvm.gc zgc. Measured on Temurin 25 at a 5.5 GB heap (NMT, design §8 "P16"):
    # ZGC's own native structures are smaller than G1's (no remembered sets), and its peak RSS was within
    # ~2 % of G1's; what ZGC needs is headroom inside the heap (no compressed oops), so the heap stays as big.
    return {
        "mc_heap_reserve_mb": HEAP_RESERVE_MB + (ONSERVER_STACK_MB if onserver_stack else 0),
        "mc_heap_reserve_pct": HEAP_RESERVE_PCT,
    }


