ICON_MAX_BYTES = 65536


PACK_ART_MAX_BYTES = 8192  # v1.2: branding.drink.texture, branding.resource_pack.glyph


def _repo_png(
    repo: ConfigRepo, field: str, rel: str | None, size: int, max_bytes: int, needs: str
) -> bytes | None:
    """A PNG of the config repo (path relative to it) with exactly size x size pixels; None when unset."""
    if not rel:
        return None
    path = (repo.root / rel).resolve()
    if not path.is_relative_to(repo.root.resolve()) or not path.is_file():
        raise RenderError([f"{field}: {rel} is not a file in the config repo"])
    data = path.read_bytes()
    if len(data) > max_bytes:
        raise RenderError([f"{field}: {rel} is {len(data)} bytes (at most {max_bytes})"])
    if data[:8] != b"\x89PNG\r\n\x1a\n" or data[12:16] != b"IHDR":
        raise RenderError([f"{field}: {rel} is not a PNG"])
    width, height = struct.unpack(">II", data[16:24])
    if (width, height) != (size, size):
        raise RenderError([f"{field}: {rel} is {width}x{height}; {needs} needs {size}x{size}"])
    return data


def icon(repo: ConfigRepo) -> bytes | None:
    """branding.icon (P17): the config repo's own 64x64 PNG (the server reads server-icon.png at start-up and
    refuses any size but 64x64: MinecraftServer.loadStatusIcon in the pinned jar); None = the product's icon.
    Rendered next to the inventory (ICON_FILE), so Ansible copies it from there."""
    return _repo_png(repo, "branding.icon", repo.server.branding.icon, 64, ICON_MAX_BYTES, "the server list")


def pack_art(repo: ConfigRepo) -> dict[str, bytes]:
    """v1.2: the config repo's own resource-pack art, checked (bytes used verbatim by mcctl/brandpack.py):
    "texture" (the drink's 16x16 item texture) and "glyph" (the 8x8 {glyph} icon); a missing key = the
    product's neutral art."""
    b = repo.server.branding
    art = {
        "texture": _repo_png(
            repo, "branding.drink.texture", b.drink.texture, 16, PACK_ART_MAX_BYTES, "an item"
        ),
        "glyph": _repo_png(
            repo, "branding.resource_pack.glyph", b.resource_pack.glyph, 8, PACK_ART_MAX_BYTES, "the glyph"
        ),
    }
    return {k: v for k, v in art.items() if v is not None}


def brand_pack_zip(repo: ConfigRepo) -> bytes | None:
    """v1.2: the resource pack (mcctl/brandpack.py) from the config repo's icon, texture and glyph (verbatim)
    or the product's neutral art, with branding.resource_pack.description; None while the pack is off."""
    b = repo.server.branding
    if not (b.enabled and b.resource_pack.enabled):
        return None
    own = pack_art(repo)
    if (own_icon := icon(repo)) is not None:
        own["icon"] = own_icon
    return brandpack.pack_zip(own, b.resource_pack.description)


def ansible_vars(repo: ConfigRepo) -> dict[str, Any]:
    """group_vars/all.yml: the tunables, players.yml, the config repo's icon (P17), the resource pack's sha1
    (v1.2: rendered, it depends on the config's art) and the lock files under the names site.yml expects."""
    locks = {"server_lock": repo.server_lock, "plugins_lock": repo.plugins_lock}
    pack = brand_pack_zip(repo)
    own = {
        "mc_brand_icon_file": ICON_FILE.relative_to("ansible").as_posix() if icon(repo) else "",
        "mc_brand_pack_sha1": brandpack.sha1(pack) if pack is not None else "",
        "mc_client_packs": client_packs(repo),  # v1.2: mc-brand's client.packs (the outdated-pack line)
    }
    return group_vars(repo.server) | players_vars(repo.players) | own | locks


def _yaml(data: dict[str, Any]) -> str:
    return HEADER + yaml.safe_dump(data, sort_keys=True, default_flow_style=False, allow_unicode=True)


def files(repo: ConfigRepo, out_dir: Path | None = None) -> dict[Path, str | bytes]:
    """Relative path -> content of every rendered file (text, or bytes for the icon and the pack). With
    out_dir (render()), the tfvars name the watchdog assets staged there (watchdog_assets_dir)."""
    cfg = repo.server
    tf = tfvars(cfg, repo.pin.repository)
    if out_dir is not None:
        tf["watchdog_assets_dir"] = str((out_dir / WATCHDOG_ASSETS_DIR).resolve())
    out: dict[Path, str | bytes] = {
        TFVARS_FILE: json.dumps(tf, indent=2, sort_keys=True) + "\n",
        BACKEND_FILE: backend(cfg),
        INVENTORY_FILE: _yaml(inventory(cfg)),
        GROUP_VARS_FILE: _yaml(ansible_vars(repo)),
    }
    if (own := icon(repo)) is not None:
        out[ICON_FILE] = own
    if (pack := brand_pack_zip(repo)) is not None:
        out[PACK_DIR / f"{brandpack.sha1(pack)}.zip"] = pack
    else:
        pack_art(repo)  # checked even while the pack is off
    if plans := client_plans(repo):
        for tier, p in plans.items():
            out[clientpack.PLAN_DIR / f"{tier}.plan.json"] = json.dumps(p, indent=1, sort_keys=True) + "\n"
        d = clientpack.load_definition()
        page = clientpack.index_for_page(
            d, plans, repo.client_lock or {}, cfg.branding.name or panel_title(cfg)
        )
        out[clientpack.INDEX_FILE] = json.dumps(page, indent=1, sort_keys=True) + "\n"
    return out


class RenderError(ValueError):
    """The config can't produce deployable output (e.g. placeholder values left in it)."""

    def __init__(self, errors: list[str]) -> None:
        super().__init__("\n".join(errors))
        self.errors = errors


def render(repo: ConfigRepo, out_dir: Path) -> list[Path]:
    """Write every file into out_dir; returns their paths. Refuses configs with placeholder values (they
    would reach the tailnet ACL and Cloudflare Access)."""
    if problems := placeholders(repo.server):
        raise RenderError(problems)
    rendered = files(repo, out_dir)
    stage_watchdog_assets(out_dir)  # not in the returned list: product files, copied
    (out_dir / VERSION_STAMP).write_text(json.dumps(version_stamp(repo), indent=1, sort_keys=True) + "\n")
    written = []
    for rel, content in rendered.items():
        path = out_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, bytes):
            path.write_bytes(content)
        else:
            path.write_text(content)
        written.append(path)
    return written


def version_stamp(repo: ConfigRepo) -> dict[str, Any]:
    """v1.3: what the Worker reports as its version: this product's (the code that renders is the code `mcctl
    apply` uploads: both run from the pin) and the config repo's pin at render time."""
    return {
        "product": __version__,
        "pin": {"sha": repo.pin.sha, "version": repo.pin.version},
        "repository": repo.pin.repository,
    }


def stage_watchdog_assets(out_dir: Path) -> None:
    """v1.2: out_dir/watchdog/ = the product's watchdog/panel/ files (without a pack/ directory: the product
    commits none), replaced as a whole on every render so no stale pack is uploaded; files() adds the pack."""
    dest = out_dir / WATCHDOG_ASSETS_DIR
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(
        PRODUCT_ASSETS, dest, ignore=lambda d, names: ["pack"] if Path(d) == PRODUCT_ASSETS else []
    )
