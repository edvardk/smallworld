def panel_title(cfg: ServerConfig) -> str:
    """The panel's heading: branding.name (P17), or without branding the MOTD without Minecraft formatting
    codes (\u00a7x), first line, <= 80 chars."""
    if cfg.branding.enabled and cfg.branding.name:
        return cfg.branding.name
    motd = cfg.minecraft.motd or f"{cfg.admin.name}'s server"
    plain = re.sub(r"\u00a7.", "", motd).replace("\\n", "\n").split("\n")[0].strip()
    return plain[:80] or f"{cfg.admin.name}'s server"


def motd(cfg: ServerConfig) -> str:
    """server.properties motd: branding.motd's lines ('&x' -> '\u00a7x'; the server's legacy-section MOTD
    parser, verified in the pinned jar: MinecraftServer.setMotd -> LegacyComponentSerializer.legacySection()),
    joined by a newline (mc_config writes it as \\n), else minecraft.motd."""
    b = cfg.branding
    if not (b.enabled and b.motd):
        return cfg.minecraft.motd or ""
    return "\n".join(
        re.sub(r"&([0-9a-fk-orA-FK-OR])", lambda m: "\u00a7" + m.group(1).lower(), ln) for ln in b.motd
    )


