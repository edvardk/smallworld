"""expiry.yml (design §3): when each admin credential expires. Names and dates only, never values.

`mcctl doctor` writes it after checking each credential live; the weekly `expiry-check` (P11) reads it plus
RDAP, so CI needs no admin token. Credentials not checked this time (not configured, or the check failed
before the expiry was learned) keep their previous entry.
"""

from __future__ import annotations

import datetime
from collections.abc import Iterable
from pathlib import Path

import yaml

from mcctl.configrepo import EXPIRY_YML, check_expiry
from mcctl.providers import CredentialCheck

HEADER = """\
# Generated by `mcctl doctor`: when each admin credential expires (names and dates only, never values).
# The weekly expiry-check reads it, so CI needs no admin token. Don't edit by hand.
"""


def merge(
    previous: list[dict[str, object]], checks: Iterable[CredentialCheck], today: datetime.date
) -> list[dict[str, object]]:
    by_name: dict[str, dict[str, object]] = {str(c["name"]): dict(c) for c in previous}
    for check in checks:
        if not check.expiry_known:
            continue
        by_name[check.credential] = {
            "name": check.credential,
            "expires_on": check.expires_on.isoformat() if check.expires_on else None,
            "checked_at": today.isoformat(),
        }
    return [by_name[n] for n in sorted(by_name)]


def dump(credentials: list[dict[str, object]]) -> str:
    """Canonical text (stdlib only, like players.yml): one flow mapping per credential, sorted by name."""
    if not credentials:
        return HEADER + "credentials: []\n"
    lines = [HEADER + "credentials:"]
    for c in credentials:
        exp = c["expires_on"] if c["expires_on"] is not None else "null"
        lines.append(f"  - {{name: {c['name']}, expires_on: {exp}, checked_at: {c['checked_at']}}}")
    return "\n".join(lines) + "\n"


def write(
    config_root: Path,
    previous: list[dict[str, object]],
    checks: Iterable[CredentialCheck],
    today: datetime.date,
) -> tuple[Path, bool]:
    """Write <config>/expiry.yml; returns (path, changed)."""
    prev = [
        {
            "name": c["name"],
            "expires_on": _iso(c["expires_on"]),
            "checked_at": _iso(c["checked_at"]),
        }
        for c in previous
    ]
    text = dump(merge(prev, checks, today))
    # Validated with the same rules `mcctl validate` applies.
    _, errors = check_expiry(yaml.safe_load(text))
    if errors:
        raise ValueError("; ".join(errors))
    path = config_root / EXPIRY_YML
    changed = not path.is_file() or path.read_text() != text
    if changed:
        path.write_text(text)
    return path, changed


def _iso(v: object) -> str | None:
    if v is None:
        return None
    return v.isoformat() if isinstance(v, datetime.date) else str(v)
